// `forge check` (architecture §4.8, A8; project contract decision 1E).
//
// A game project is checked against this engine:
// 1. its manifest normalises, its `sdkVersion` fits the engine's SDK and the
//    content packs it names exist in the engine (A9);
// 2. `.forge/tsconfig.json` is (re)written: the engine's own compiler options,
//    and paths for `@forge/sdk` and `@forge/editor-sdk` only, resolved from
//    the engine root (no fixed `../../Forge`);
// 3. the project compiles;
// 4. its imports stay inside the contract, read from the AST: relative
//    imports that stay in the project, `@forge/sdk`, and `@forge/editor-sdk`
//    from editor files only (`editor.ts`, `src/editor/`). `three`, engine
//    paths, Node modules, other packages are refused. Resolution alone cannot
//    enforce this: a project inside the engine repository (samples/) would
//    find the engine's node_modules.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import ts from "typescript";
import {
  checkSdkCompatibility,
  normalizeProjectManifest,
  PROJECT_FILE,
  SDK_VERSION,
  type Issue,
  type ProjectManifest,
} from "../../src/core/index.ts";
import { contentPackProblems } from "../assets/engineContent.ts";

export const SDK_SPECIFIER = "@forge/sdk";
export const EDITOR_SDK_SPECIFIER = "@forge/editor-sdk";
export const GENERATED_TSCONFIG = ".forge/tsconfig.json";

export interface ProjectProblem {
  /** Project-relative file; "" for the project as a whole. */
  readonly file: string;
  readonly line: number;
  readonly code: string;
  readonly message: string;
}

export interface LoadedProject {
  readonly root: string;
  readonly manifest: ProjectManifest | null;
  readonly problems: ProjectProblem[];
}

const slashes = (path: string): string => path.split(sep).join("/");

export interface LoadProjectOptions {
  /** When given, the content packs the manifest names must exist in this engine. */
  readonly engineRoot?: string;
  readonly engineSdk?: string;
}

/** Reads and checks `forge.project.json`, including the SDK version and the content packs. */
export async function loadProject(root: string, options: LoadProjectOptions = {}): Promise<LoadedProject> {
  const engineSdk = options.engineSdk ?? SDK_VERSION;
  const problems: ProjectProblem[] = [];
  let raw: unknown;
  try {
    raw = JSON.parse(await readFile(join(root, PROJECT_FILE), "utf8"));
  } catch (error) {
    problems.push({ file: PROJECT_FILE, line: 0, code: "no-manifest", message: `Cannot read ${PROJECT_FILE}: ${(error as Error).message}` });
    return { root, manifest: null, problems };
  }
  const result = normalizeProjectManifest(raw, { strict: true });
  for (const found of result.issues as readonly Issue[]) {
    problems.push({ file: PROJECT_FILE, line: 0, code: found.code, message: `${found.path === "" ? "" : `${found.path}: `}${found.message}` });
  }
  const manifest = result.value;
  if (manifest) {
    const fit = checkSdkCompatibility(engineSdk, manifest.sdkVersion);
    if (!fit.ok) problems.push({ file: PROJECT_FILE, line: 0, code: "sdk-version", message: fit.reason });
    if (options.engineRoot !== undefined) {
      for (const message of await contentPackProblems(options.engineRoot, manifest.contentPacks)) {
        problems.push({ file: PROJECT_FILE, line: 0, code: "content-pack", message: `contentPacks: ${message}` });
      }
    }
  }
  return { root, manifest, problems };
}

/** The tsconfig a project extends: the engine's compiler options and the two SDK paths. */
export async function writeProjectTsconfig(projectRoot: string, engineRoot: string): Promise<string> {
  const base = ts.readConfigFile(join(engineRoot, "tsconfig.base.json"), ts.sys.readFile);
  if (base.error) throw new Error(ts.flattenDiagnosticMessageText(base.error.messageText, "\n"));
  const compilerOptions = {
    ...(base.config as { compilerOptions: Record<string, unknown> }).compilerOptions,
    lib: ["ES2022", "DOM", "DOM.Iterable"],
    types: [],
    paths: {
      [SDK_SPECIFIER]: [slashes(join(engineRoot, "src/sdk/index.ts"))],
      [EDITOR_SDK_SPECIFIER]: [slashes(join(engineRoot, "src/editor-sdk/index.ts"))],
    },
  };
  const text = `${JSON.stringify(
    {
      "//": "Generated by forge check / forge dev from the engine at the path below. Do not edit; do not commit.",
      compilerOptions,
    },
    null,
    2,
  )}\n`;
  const path = join(projectRoot, GENERATED_TSCONFIG);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, text);
  return path;
}

function isEditorFile(projectRelative: string): boolean {
  return projectRelative.endsWith("/editor.ts") || projectRelative === "editor.ts" || projectRelative.startsWith("src/editor/");
}

/** Module specifiers a file names: imports, re-exports, dynamic imports, import types. */
export function moduleSpecifiers(source: ts.SourceFile): { specifier: string; line: number }[] {
  const out: { specifier: string; line: number }[] = [];
  const add = (node: ts.Node, literal: ts.Expression | undefined): void => {
    if (literal && ts.isStringLiteralLike(literal)) {
      out.push({ specifier: literal.text, line: source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1 });
    }
  };
  const visit = (node: ts.Node): void => {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) add(node, node.moduleSpecifier);
    else if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference)) {
      add(node, node.moduleReference.expression);
    } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) add(node, node.arguments[0]);
    else if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)) add(node, node.argument.literal);
    ts.forEachChild(node, visit);
  };
  visit(source);
  return out;
}

/** Import boundary problems of one project file. */
export function boundaryProblems(source: ts.SourceFile, projectRoot: string): ProjectProblem[] {
  const file = slashes(relative(projectRoot, source.fileName));
  const problems: ProjectProblem[] = [];
  for (const { specifier, line } of moduleSpecifiers(source)) {
    if (specifier === SDK_SPECIFIER) continue;
    if (specifier === EDITOR_SDK_SPECIFIER) {
      if (!isEditorFile(file)) {
        problems.push({ file, line, code: "editor-sdk-outside-editor", message: `${EDITOR_SDK_SPECIFIER} is for editor files (editor.ts, src/editor/); the game must not load the editor.` });
      }
      continue;
    }
    if (specifier.startsWith("./") || specifier.startsWith("../")) {
      const target = slashes(relative(projectRoot, resolve(dirname(source.fileName), specifier)));
      if (target === ".." || target.startsWith("../") || /^[A-Za-z]:/.test(target)) {
        problems.push({ file, line, code: "outside-project", message: `"${specifier}" leaves the project. A game imports the engine through ${SDK_SPECIFIER} only.` });
      }
      continue;
    }
    problems.push({
      file,
      line,
      code: "not-in-contract",
      message: `"${specifier}" is not part of the contract: a game imports ${SDK_SPECIFIER}${isEditorFile(file) ? ` and ${EDITOR_SDK_SPECIFIER}` : ""} and its own files only.`,
    });
  }
  return problems;
}

export interface CheckResult {
  readonly ok: boolean;
  readonly manifest: ProjectManifest | null;
  readonly problems: readonly ProjectProblem[];
}

/** Manifest, SDK version, generated tsconfig, compile, import boundary. */
export async function checkProject(projectRoot: string, engineRoot: string, engineSdk = SDK_VERSION): Promise<CheckResult> {
  const root = resolve(projectRoot);
  const loaded = await loadProject(root, { engineRoot: resolve(engineRoot), engineSdk });
  const problems = [...loaded.problems];
  if (!loaded.manifest || problems.some((problem) => problem.code === "sdk-version")) {
    return { ok: false, manifest: loaded.manifest, problems };
  }
  await writeProjectTsconfig(root, resolve(engineRoot));

  const configPath = join(root, "tsconfig.json");
  const parsed = ts.getParsedCommandLineOfConfigFile(configPath, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
      problems.push({ file: "tsconfig.json", line: 0, code: "tsconfig", message: ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n") });
    },
  });
  if (!parsed) return { ok: false, manifest: loaded.manifest, problems };
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  for (const diagnostic of [...parsed.errors, ...ts.getPreEmitDiagnostics(program)]) {
    const file = diagnostic.file ? slashes(relative(root, diagnostic.file.fileName)) : "";
    const line = diagnostic.file && diagnostic.start !== undefined ? diagnostic.file.getLineAndCharacterOfPosition(diagnostic.start).line + 1 : 0;
    problems.push({ file, line, code: `TS${diagnostic.code}`, message: ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n") });
  }
  for (const source of program.getSourceFiles()) {
    const rel = slashes(relative(root, source.fileName));
    if (rel.startsWith("../") || /^[A-Za-z]:/.test(rel) || rel.startsWith("node_modules/") || rel.startsWith(".forge/")) continue;
    problems.push(...boundaryProblems(source, root));
  }
  return { ok: problems.length === 0, manifest: loaded.manifest, problems };
}

export function formatProblem(problem: ProjectProblem): string {
  return `${problem.file}${problem.line > 0 ? `:${problem.line}` : ""} ${problem.code}: ${problem.message}`;
}
